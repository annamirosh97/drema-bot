// Страница юридического документа.
//
// Открыта без пароля: её адрес уходит людям в сообщениях о согласиях и
// попадает в журнал, так что она должна отвечать всем и всегда.
//
// Текст показываем как есть, моноширинным блоком: это точный файл той
// версии, которую видел человек, и пересказывать его разметкой — значит
// показывать не то, на что он согласился.

import { html, page, raw } from "./html";

export function renderLegalPage(title: string, version: string, text: string): string {
  return page(
    title,
    html`<h1>${title}</h1>
      <p class="muted">Версия ${version}</p>
      <div class="card"><pre>${text}</pre></div>
      ${raw(
        text.includes("[ЗАГЛУШКА")
          ? html`<p class="muted">Документ готовится. Здесь появится его финальный текст.</p>`
          : ""
      )}`
  );
}
