const SORTED_NUMBERS = [...QUESTIONS].map((q) => q.number).sort((a, b) => a - b);
const BY_NUMBER = new Map(QUESTIONS.map((q) => [q.number, q]));

export function getQuestion(number: number): QuestionDef {
  const q = BY_NUMBER.get(number);
  if (!q) throw new Error(`Вопрос №${number} не найден в questions.ts`);
  return q;
}

export function getFirstQuestionNumber(): number {
  return SORTED_NUMBERS[0];
}

// ── Счётчик «→ Вопрос N/M» ──────────────────────────────────────────
//
// Раньше он был вписан в текст каждого вопроса руками, и стоило удалить
// или добавить вопрос, как вся нумерация разъезжалась. Теперь считается
// сам.
//
// В счёт не идут два вида экранов: вводный (у него единственная кнопка
// «Продолжить» — это переход, а не вопрос) и условный 4.5, который
// показывается не всем. Иначе у одних людей анкета была бы «из 18
// вопросов», а у других «из 17».

const COUNTED_NUMBERS = [...QUESTIONS]
  .filter((q) => q.options?.length !== 1 && !q.skipUnless)
  .map((q) => q.number)
  .sort((a, b) => a - b);

export const COUNTED_QUESTIONS_TOTAL = COUNTED_NUMBERS.length;

// Текст вопроса со счётчиком на конце. У экранов, которые в счёт не
// идут, текст возвращается как есть.
export function questionTextWithCounter(question: QuestionDef): string {
  const position = COUNTED_NUMBERS.indexOf(question.number);
  if (position === -1) return question.text;

  // trimEnd страхует от лишних переносов, если в тексте остался хвост.
  return `${question.text.trimEnd()}\n\n → Вопрос ${position + 1}/${COUNTED_QUESTIONS_TOTAL}`;
}

// Ближайший существующий вопрос, начиная с указанного номера. Нужен
// тем, кто в момент деплоя стоял на вопросе, которого больше нет:
// анкета должна продолжиться со следующего, без сообщений об ошибке.
export function nearestQuestionNumber(number: number): number | null {
  if (BY_NUMBER.has(number)) return number;
  return SORTED_NUMBERS.find((n) => n > number) ?? null;
}

// Возвращает номер следующего вопроса с учётом пропуска условных
// вопросов (сейчас это только 4.5), или null, если анкета закончена.
export function getNextQuestionNumber(
  current: number,
  answersSoFar: Record<number, string>
): number | null {
  let idx = SORTED_NUMBERS.indexOf(current);
  while (true) {
    idx++;
    if (idx >= SORTED_NUMBERS.length) return null;
    const candidate = getQuestion(SORTED_NUMBERS[idx]);
    if (candidate.skipUnless && !candidate.skipUnless(answersSoFar)) {
      continue;
    }
    return candidate.number;
  }
}
