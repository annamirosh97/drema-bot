export type InputType = "number" | "single_choice" | "multi_choice" | "free_text";

export interface QuestionDef {
  number: number; // 3.5 — это реальный отдельный "вопрос", как и было в Sheets
  text: string;
  type: InputType;
  options?: string[]; // для multi_choice обязательно включает "Готово"
  // Картинка к вопросу: текст уходит подписью к фото (лимит подписи в Telegram — 1024 символа).
  photoUrl?: string;
  min?: number;
  max?: number;
  // Если true — выход за пределы [min, max] завершает анкету (сейчас только вопрос 1).
  outOfRangeEndsFlow?: boolean;
  // Красный флаг: если среди ответов есть хотя бы одно из этих значений —
  // анкета немедленно и жёстко останавливается.
  redFlagValues?: string[];
  // Жёлтый флаг: анкета продолжается как обычно, но категория помечается
  // для ручной проверки при подготовке рекомендаций (см. /prep в админке).
  yellowFlagValues?: string[];
  yellowFlagLabel?: string;
  // Вопрос показывается только если функция вернёт true.
  // Используется для ветки 3 → 3.5 ("Другое").
  skipUnless?: (answers: Record<number, string>) => boolean;
}

