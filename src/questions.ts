export type InputType = "number" | "single_choice" | "multi_choice" | "free_text";

export interface QuestionDef {
  number: number; // 3.5 — это реальный отдельный "вопрос", как и было в Sheets
  text: string;
  type: InputType;
  options?: string[]; // для multi_choice обязательно включает "Готово"
  // Короткая подпись для итоговой анкеты в конце. Нужна там, где полный
  // текст вопроса начинается с инструкции или слишком длинный, чтобы
  // список из 20 пунктов оставался читаемым. Если не задана — берётся
  // сам текст вопроса, обрезанный по длине.
  shortLabel?: string;
  // Картинка к вопросу: текст уходит подписью к фото (лимит подписи в Telegram — 1024 символа).
  photoUrl?: string;
  min?: number;
  max?: number;
  // Если true — выход за пределы [min, max] завершает анкету (сейчас только вопрос 1).
  outOfRangeEndsFlow?: boolean;
  // Флаги с 15.10.2026 на логику анкеты не влияют: бот не спрашивает о
  // здоровье, а недоношенность методология учитывает через
  // скорректированный возраст. Поля оставлены, чтобы не терять разметку
  // вопроса 2 и чтобы старые записи оставались читаемыми.
  redFlagValues?: string[];
  yellowFlagValues?: string[];
  yellowFlagLabel?: string;
  // Вопрос показывается только если функция вернёт true.
  // Используется для ветки 4 → 4.5 ("Другое").
  skipUnless?: (answers: Record<number, string>) => boolean;
}

