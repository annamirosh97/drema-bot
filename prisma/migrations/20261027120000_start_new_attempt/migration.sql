-- /start у человека с завершённой анкетой заводит новое прохождение
-- молча, без экрана подтверждения. Отдельное событие, а не
-- restart_confirmed: иначе в /stats перезапусками считалось бы то,
-- чего никто не подтверждал, а возвраты через /start — отдельная и
-- полезная цифра.
--
-- IF NOT EXISTS и отдельной транзакцией: ALTER TYPE ... ADD VALUE
-- нельзя выполнять в одной транзакции с использованием значения.
ALTER TYPE "OfferEventType" ADD VALUE IF NOT EXISTS 'start_new_attempt';
