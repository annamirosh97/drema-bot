-- Черновик модели отдельно от того, что ушло родителю.
--
-- ТЗ админки требует, чтобы исходный черновик не менялся, а правки были
-- видны как diff. До сих пор правка через /send затирала текст модели
-- без следа, и сравнивать было нечего.
ALTER TABLE "Recommendation" ADD COLUMN "aiMessage1" TEXT;
ALTER TABLE "Recommendation" ADD COLUMN "aiMessage2" TEXT;

-- У существующих разборов исходник восстановить нельзя: правки, если
-- они были, уже затёрли его. Копируем текущий текст — для неправленых
-- разборов это и есть черновик модели, для правленых diff будет пустым,
-- и это честнее, чем показывать выдуманную разницу.
UPDATE "Recommendation"
SET "aiMessage1" = "message1", "aiMessage2" = "message2"
WHERE "message1" IS NOT NULL;
